/**
 * Input validation and shell quoting.
 *
 * This tool interpolates user-controllable strings (--pkg / --appid / artifact
 * relative paths) into `adb shell` command strings. `adb shell` runs through the
 * device's `sh`, so every interpolation must be **allow-list validated** before
 * concatenation and **single-quote escaped** when quoted.
 *
 * Example attack surface (without validation):
 *   --pkg "com.x'; rm -rf /storage/emulated/0/Android/data/com.x; echo '"
 *   -> the concatenated command becomes rm -f 'dir/com.x'; rm -rf ...; echo ''
 *
 * Both defences are required:
 *   1) Allow-list: the character set for pkg / appid / rel is restricted, so
 *      command separators can never get in.
 *   2) Escaping: even if the allow-list were bypassed (or relaxed later),
 *      single-quote escaping still blocks the injection.
 */
import path from 'node:path'

/**
 * POSIX sh single-quote escaping.
 *
 * A single quote cannot appear inside a single-quoted string. The standard
 * approach is to close the quote, escape the quote, and reopen it:
 *   foo'  ->  'foo'\''bar'
 * The shell parses '\'' as a literal single quote.
 */
export function shellQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`
}

/** Android package name: dot-separated segments, each starting with a letter. */
const PKG_RE = /^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z0-9_]+)*$/

/** uni appid: generated by dcloud, e.g. __UNI__ABCDEF. */
const APPID_RE = /^[A-Za-z0-9_-]+$/

/** One segment of a uni-app page path, e.g. `index` in `pages/index/index`. */
const PAGE_SEGMENT_RE = /^[A-Za-z0-9_-]+$/

/**
 * Allowed characters of a URL query string (`a=1&b=2`).
 *
 * The value is never interpolated into a shell command (it travels as a JSON
 * string inside a CDP expression), so this is a typo guard rather than a
 * security boundary. Percent-encoding is allowed, which covers non-ASCII
 * values. Shell and JS metacharacters are deliberately excluded so that a
 * pasted command fragment is rejected instead of silently travelling on.
 */
const PAGE_QUERY_RE = /^[A-Za-z0-9._~%&=+,:@/-]*$/

/**
 * Allowed characters for a single path segment of a relative artifact path.
 * Derived from real build output: `@` and `+` do occur in dist.
 */
const REL_SEGMENT_RE = /^[A-Za-z0-9._@+~()[\]-]+$/

/** Validate an Android package name. */
export function assertPackageName(pkg) {
  if (typeof pkg !== 'string' || !PKG_RE.test(pkg)) {
    throw new Error(
      `Invalid application package name: ${JSON.stringify(pkg)}\n` +
        `  A package name may only contain letters, digits, underscores and dots, ` +
        `and every segment must start with a letter.`
    )
  }
  return pkg
}

/** Validate a uni appid. */
export function assertAppid(appid) {
  if (typeof appid !== 'string' || !APPID_RE.test(appid)) {
    throw new Error(
      `Invalid appid: ${JSON.stringify(appid)}\n` +
        `  An appid may only contain letters, digits, underscores and hyphens.`
    )
  }
  return appid
}

/**
 * Validate a uni-app page path and normalise it to the `pages/a/b` form.
 *
 * A leading slash is accepted (HBuilderX writes `/pages/a/b` in its launch
 * configuration) and stripped, because the runtime reports routes without it.
 */
export function assertPagePath(page) {
  if (typeof page !== 'string' || page.length === 0) {
    throw new Error('Invalid page path: empty')
  }
  const normalized = page.replace(/^\/+/, '')
  const segments = normalized.split('/')
  if (segments.length < 2) {
    throw new Error(
      `Invalid page path: ${JSON.stringify(page)}\n` +
        `  A uni-app page path needs at least a directory and a file, for example pages/index/index.`
    )
  }
  for (const seg of segments) {
    if (!PAGE_SEGMENT_RE.test(seg)) {
      throw new Error(
        `Invalid page path: ${JSON.stringify(page)}\n` +
          `  Every segment may only contain letters, digits, underscores and hyphens.`
      )
    }
  }
  return normalized
}

/** Validate a URL query string (`a=1&b=2`). An empty string is allowed. */
export function assertPageQuery(query) {
  if (query === undefined || query === null || query === '') return ''
  if (typeof query !== 'string' || !PAGE_QUERY_RE.test(query)) {
    throw new Error(
      `Invalid page query: ${JSON.stringify(query)}\n` +
        `  Expected a URL query string such as a=1&b=2 (percent-encode non-ASCII values).`
    )
  }
  return query
}

/**
 * Split a page argument into its path and the query it carries.
 *
 * The `--page` value may be written as a whole url (`/pages/a/b?x=1`), the same
 * way HBuilderX writes it, so the query has to be separated before the path is
 * validated.
 *
 * @param {string} page page path, optionally with a query (`pages/a/b?x=1`)
 * @returns {{path: string, query: string}}
 */
export function splitPageUrl(page) {
  if (typeof page !== 'string') return { path: page, query: '' }
  const i = page.indexOf('?')
  if (i === -1) return { path: page, query: '' }
  return { path: page.slice(0, i), query: page.slice(i + 1) }
}

/**
 * Build the `uni.reLaunch` url from a page path and a query string.
 *
 * The query may be given inline in the page (`pages/a/b?x=1`) or through the
 * separate `--query` option; when both are present the inline part comes first.
 *
 * @param {string} page page path (`pages/a/b`, a leading slash is accepted)
 * @param {string} [query] query string (`a=1&b=2`)
 * @returns {string} `/pages/a/b?a=1&b=2`
 */
export function buildPageUrl(page, query = '') {
  const parts = splitPageUrl(page)
  const inline = assertPageQuery(parts.query)
  const extra = assertPageQuery(query)
  const search = [inline, extra].filter(Boolean).join('&')
  return `/${assertPagePath(parts.path)}${search ? `?${search}` : ''}`
}

/**
 * Validate an artifact relative path (dist -> device-relative path).
 *
 * Rejects:
 *   - absolute paths
 *   - empty segments, `.`, `..` (prevents traversal outside the www directory)
 *   - NUL bytes
 *   - any character outside the allow-list (spaces, quotes, `;`, `$`, backticks
 *     and other shell metacharacters)
 */
export function assertRelPath(rel) {
  if (typeof rel !== 'string' || rel.length === 0) {
    throw new Error('Invalid artifact relative path: empty')
  }
  if (rel.includes('\0')) {
    throw new Error('Invalid artifact relative path: contains a NUL character')
  }
  if (path.isAbsolute(rel) || rel.startsWith('/') || /^[A-Za-z]:/.test(rel)) {
    throw new Error(`Invalid artifact relative path (absolute paths are not allowed): ${JSON.stringify(rel)}`)
  }
  for (const seg of rel.split('/')) {
    if (!seg || seg === '.' || seg === '..') {
      throw new Error(
        `Invalid artifact relative path (empty segments and . / .. are not allowed): ${JSON.stringify(rel)}`
      )
    }
    if (!REL_SEGMENT_RE.test(seg)) {
      throw new Error(
        `Invalid artifact relative path (contains disallowed characters): ${JSON.stringify(rel)}\n` +
          `  Allowed characters: letters, digits, _ . @ + ~ ( ) [ ] -`
      )
    }
  }
  return rel
}
